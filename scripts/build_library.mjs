import {
  mkdirSync,
  readFileSync,
  writeFileSync,
  copyFileSync,
  existsSync,
} from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { revision } from "../packages/product-core/edition.ts";
import { sheetFor } from "../packages/product-core/aircraft.ts";
import { pdf } from "../packages/print-export/sheets.ts";
import { workshopModels } from "../packages/geometry/workshop.ts";
import { makeFoldedButterfly, foldedPdf } from "../packages/folded-butterfly/index.ts";
import { makePlane, planePdf, planeCatalog } from "../packages/planes/index.ts";
import { makeK2, k2Pdf, k2FinishedSvg, k2BuildSteps } from "../packages/folded-butterfly/k2-sheet.ts";
import { makeK3, k3Pdf, k3FinishedSvg, k3BuildSteps, k3SpanRange } from "../packages/folded-butterfly/k3-sheet.ts";
import { k3Designs } from "../packages/folded-butterfly/k3-designs.ts";
import { calibrationHtml, documentCss } from "../apps/editor/assets/brand/print.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const editor = join(root, "apps/editor"),
  library = join(editor, "library");
mkdirSync(library, { recursive: true });
copyFileSync(
  join(root, "packages/field-guide/species.json"),
  join(editor, "assets/atlas/species.json"),
);
const speciesGuide = JSON.parse(readFileSync(join(root, "packages/field-guide/species.json"), "utf8"));
const baselines = Object.fromEntries(workshopModels.map(({ species, parameters, geometry }) => {
  const entry = speciesGuide.find(item => item.id === species);
  return [species, {
    span: parameters.span_mm, rootAngle: geometry.target_dihedral_deg,
    tab: geometry.tab_depth_mm, clip: geometry.clip_rear_from_nose_mm,
    names: Object.fromEntries(['en', 'es', 'ru'].map(lang => [lang, entry[lang].common_name])),
    scientific: entry.scientific_name,
  }];
}));
writeFileSync(join(editor, 'assets/atlas/baselines.js'), '// Generated by scripts/build_library.mjs from the printable geometry.\nexport const baselines = ' + JSON.stringify(baselines, null, 2) + '\n');
// The opening specimen is the finished K3 seen from above. The retired K2 views stay for old pages.
for (const model of workshopModels) {
  for (const { appearance_id } of model.appearances) {
    const plan = makeK2({ species: model.species, appearance_id })
    writeFileSync(join(editor, 'assets/atlas', model.species + '-k2-' + appearance_id + '.svg'), k2FinishedSvg(plan))
    writeFileSync(join(editor, 'assets/atlas', model.species + '-k3-' + appearance_id + '.svg'), k3FinishedSvg(makeK3({ species: model.species, appearance_id })))
  }
  // K3-only designs (k3-designs.ts) have a K3 poster only.
  for (const appearance_id of k3Designs) {
    writeFileSync(join(editor, 'assets/atlas', model.species + '-k3-' + appearance_id + '.svg'), k3FinishedSvg(makeK3({ species: model.species, appearance_id })))
  }
}
// Keep static page generation available to the dependency-free deployment check.
const diagrams = Object.fromEntries(workshopModels.map(({species}) => [
  species, k2BuildSteps(makeK2({species})).map(step => step.diagram)
]))
const instructions = Object.fromEntries(['en','es','ru'].map(locale => [
  locale, k2BuildSteps(makeK2({locale})).map(({title,action,check}) => ({title,action,check}))
]))
writeFileSync(join(editor,'assets/atlas/k2-lessons.js'),
  '// Generated from the K2 print guide by scripts/build_library.mjs.\n' +
  'export const diagrams = ' + JSON.stringify(diagrams) + '\nexport const instructions = ' + JSON.stringify(instructions) + '\n')
const facts = Object.fromEntries(workshopModels.map(({ species }) => {
  const plan = makeK2({species});
  return [species, {span:plan.span_mm,angle:plan.dihedral_deg,tip:plan.tip_height_mm}];
}));
writeFileSync(join(editor,'assets/atlas/k2-facts.js'),'export const k2Facts = '+JSON.stringify(facts,null,2)+'\n');
// K3, the current folded butterfly: step pictures, words and the numbers the pages show.
writeFileSync(join(editor,'assets/atlas/k3-lessons.js'),
  '// Generated from the K3 print guide by scripts/build_library.mjs.\n' +
  'export const diagrams = ' + JSON.stringify(Object.fromEntries(workshopModels.map(({species}) => [
    species, k3BuildSteps(makeK3({species})).map(step => step.diagram)]))) +
  '\nexport const instructions = ' + JSON.stringify(Object.fromEntries(['en','es','ru'].map(locale => [
    locale, k3BuildSteps(makeK3({locale})).map(({title,action,check}) => ({title,action,check}))]))) + '\n')
const k3Facts = Object.fromEntries(workshopModels.map(({ species }) => {
  const plan = makeK3({species});
  return [species, {span:plan.span_mm,angle:plan.dihedral_deg,tip:plan.tip_height_mm,sweep:Math.round(plan.estimate.sweep_deg),balance:plan.balance_from_nose_mm}];
}));
writeFileSync(join(editor,'assets/atlas/k3-facts.js'),'// Generated by scripts/build_library.mjs from makeK3. Model estimates, not measurements.\nexport const k3Facts = '+JSON.stringify(k3Facts,null,2)+'\n');
const swatches = Object.fromEntries(workshopModels.map(({ species, palettes }) => [
  species, Object.fromEntries(Object.entries(palettes).map(([id, { base, sun, ink }]) => [
    id, [base, sun, ink],
  ])),
]));
writeFileSync(join(editor, 'assets/atlas/swatches.js'), '// Generated by scripts/build_library.mjs from the print palettes.\nexport const butterflySwatches = ' + JSON.stringify(swatches, null, 2) + '\n');
const { paperSizes, sheetCatalog, sheetIdFor, sheetLocales, sheetPath } = await import('../apps/editor/family-sheets.js');
writeFileSync(
  join(editor, 'assets/atlas/print-catalog.json'),
  JSON.stringify({ sheets: sheetCatalog, papers: paperSizes, locales: sheetLocales }, null, 2) + '\n',
)
const lesson = [
  "docs/outreach/paper-flight-lesson.md",
  "guides/paper-flight-lesson.md",
]
  .map((path) => join(root, path))
  .find((path) => existsSync(path));
if (!lesson) throw Error("Missing family lesson source");
const md = readFileSync(lesson, "utf8");
const [english, russian] = md.split("## English\n")[1].split("## По-русски\n");
const [ruLesson, end] = russian.split("Original lesson text and tables");
const spanishLesson = readFileSync(lesson.replace(/\.md$/, ".es.md"), "utf8");
const [spanishHeading, ...spanishBody] = spanishLesson.trim().split("\n");
const lessonTitles = {
  en: "Can a paper butterfly turn?",
  ru: "Может ли бумажная бабочка повернуть?",
  es: spanishHeading.replace(/^# /, ""),
};
const lessonCopy = {
  es: spanishBody.join("\n"),
  en:
    english +
    "\nOriginal lesson text and tables" +
    end.split("\nТекст занятия")[0],
  ru: ruLesson + "\nТекст занятия" + end.split("\nТекст занятия")[1],
};
for (const locale of sheetLocales) {
  const title = lessonTitles[locale];
  const home = { en: "", ru: "ru.html", es: "es.html" }[locale];
  const body = Bun.markdown.html(lessonCopy[locale]);
  writeFileSync(
    join(library, "family-lesson-" + locale + ".html"),
    '<!doctype html><html lang="' +
      locale +
      '"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>' +
      title +
      ' · Open Flight</title><style>' +
      documentCss({ fontsBase: '../assets/fonts/' }) +
      '</style><main><header><a href="https://openflight.design/' +
      home +
      '">Open Flight</a></header><h1>' +
      title +
      "</h1>" +
      body +
      calibrationHtml(locale) +
      "</main></html>",
  );
  for (const paper of paperSizes) {
    for (const m of workshopModels) {
      const folded = makeFoldedButterfly({species:m.species,paper}, locale);
      writeFileSync(join(editor, sheetPath(sheetIdFor(m.species, 'k1'), paper, locale)), foldedPdf(folded));
      const seed = revision(
        m.model,
        m.baseline_revision,
        m.name,
        m.parameters,
        m.appearance_id,
        null,
        "original",
        "2026-11-23T00:00:00Z",
        m.species,
      );
      writeFileSync(
        join(editor, sheetPath(sheetIdFor(m.species, 'w1'), paper, locale)),
        pdf(sheetFor(seed.dto, paper, locale)),
      );
      writeFileSync(
        join(editor, sheetPath(sheetIdFor(m.species, 'k2'), paper, locale)),
        k2Pdf(makeK2({ species: m.species, paper, locale })),
      );
      writeFileSync(
        join(editor, sheetPath(sheetIdFor(m.species, 'k3'), paper, locale)),
        k3Pdf(makeK3({ species: m.species, paper, locale })),
      );
    }
    for (const m of planeCatalog) {
      const plan = makePlane({ model_id: m.model_id, paper }, locale);
      writeFileSync(
        join(editor, sheetPath(sheetIdFor(m.model_id), paper, locale)),
        planePdf(plan),
      );
    }
  }
}
console.log("Built " + sheetCatalog.length * paperSizes.length * sheetLocales.length + " calibrated starter PDFs and three offline family lessons.");
