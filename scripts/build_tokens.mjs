// Copies apps/editor/tokens.css into apps/editor/assets/brand/tokens.js for code that cannot read CSS:
// the PDF generators (Node and browser) and the identity builder. tokens.css stays the source of truth.
// Usage: node scripts/build_tokens.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const cssPath = root + 'apps/editor/tokens.css'
const outPath = root + 'apps/editor/assets/brand/tokens.js'

export function readTokens(css = readFileSync(cssPath, 'utf8')) {
  const body = css.replace(/\/\*[\s\S]*?\*\//g, '').match(/:root\s*{([\s\S]*?)}/)[1]
  const raw = {}
  for (const [, name, value] of body.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) raw[name] = value.trim()
  const resolve = (value, seen = []) =>
    value.replace(/var\(--([\w-]+)\)/g, (_, n) => {
      if (seen.includes(n) || !(n in raw)) throw Error('Unresolved token --' + n)
      return resolve(raw[n], [...seen, n])
    })
  return Object.fromEntries(Object.entries(raw).map(([k, v]) => [k, resolve(v)]))
}

const mm = (v) => {
  const m = v.match(/^([\d.]+)mm$/)
  if (!m) throw Error('Expected mm: ' + v)
  return +m[1]
}
const pt = (v) => {
  const m = v.match(/^([\d.]+)pt$/)
  if (!m) throw Error('Expected pt: ' + v)
  return +m[1]
}
const dash = (v) => v.split(/\s+/).map(mm)

export function moduleSource(t = readTokens()) {
  const color = Object.fromEntries(
    Object.entries(t)
      .filter(([k, v]) => k.startsWith('color-') && /^#[0-9a-f]{6}$/i.test(v))
      .map(([k, v]) => [k.slice(6).replace(/-(\w)/g, (_, c) => c.toUpperCase()), v.toUpperCase()]),
  )
  const print = {
    ink: t['print-ink'].toUpperCase(),
    muted: t['print-muted'].toUpperCase(),
    text: {
      min: pt(t['print-text-min']),
      body: pt(t['print-text-body']),
      step: pt(t['print-text-step']),
      title: pt(t['print-text-title']),
      display: pt(t['print-text-display']),
    },
    leading: +t['print-leading'],
    line: { min: mm(t['print-line-min']), fold: mm(t['print-line-fold']), cut: mm(t['print-line-cut']) },
    dash: {
      valley: dash(t['print-dash-valley']),
      mountain: dash(t['print-dash-mountain']),
      guide: dash(t['print-dash-guide']),
    },
    safe: mm(t['print-safe']),
    margin: mm(t['print-margin']),
    calibration: mm(t['print-calibration']),
    brandMax: mm(t['print-brand-max']),
  }
  const screenDash = { valley: t['dash-valley'], mountain: t['dash-mountain'], guide: t['dash-guide'] }
  return (
    '// Generated by scripts/build_tokens.mjs from apps/editor/tokens.css. Do not edit.\n' +
    'export const color = ' +
    JSON.stringify(color, null, 2) +
    '\n// Screen dash patterns (SVG user units).\nexport const dash = ' +
    JSON.stringify(screenDash, null, 2) +
    '\nexport const print = ' +
    JSON.stringify(print, null, 2) +
    '\n'
  )
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = moduleSource()
  if (process.argv.includes('--check')) {
    const current = readFileSync(outPath, 'utf8')
    if (current !== next) {
      console.error('assets/brand/tokens.js is out of date. Run node scripts/build_tokens.mjs')
      process.exit(1)
    }
    console.log('Token module matches tokens.css')
  } else {
    writeFileSync(outPath, next)
    console.log('Wrote ' + outPath)
  }
}
