import { readFile, stat, writeFile } from 'node:fs/promises'
import { artPath, bookStyles } from '../apps/editor/book-model.js'
import { paperSizes, sheetCatalog, sheetLocales } from '../apps/editor/family-sheets.js'
import { createBook } from '../packages/print-export/family-book.js'

const editor = new URL('../apps/editor/', import.meta.url)
const assets = new Map()
const loadAsset = path => {
  if (!assets.has(path)) assets.set(path, readFile(new URL(path, editor)))
  return assets.get(path)
}

const styles = {}
for (const style of bookStyles) {
  const sizes = await Promise.all(sheetCatalog.map(async ({ id }) => [
    id,
    (await stat(new URL(artPath(id, style), editor))).size,
  ]))
  styles[style] = Object.fromEntries(sizes)
}

const ordinaryPair = sheetCatalog.filter(({ family }) => family === 'airplane').slice(0, 2).map(({ id }) => id)
const sharedPair = sheetCatalog.filter(({ sharedGuide }) => sharedGuide).slice(0, 2).map(({ id }) => id)
const sizes = {}
for (const lang of sheetLocales) {
  sizes[lang] = {}
  for (const paper of paperSizes) {
    const measure = async sheets =>
      (await createBook({ lang, paper, sheets, style: 'studio' }, { loadAsset })).byteLength
    const singles = Object.fromEntries(await Promise.all(sheetCatalog.map(async ({ id }) => [
      id,
      await measure([id]),
    ])))
    const overlap = async pair => singles[pair[0]] + singles[pair[1]] - await measure(pair)
    const frontMatter = await overlap(ordinaryPair)
    const sharedGuide = await overlap(sharedPair) - frontMatter
    sizes[lang][paper] = { singles, frontMatter, sharedGuide }
  }
}

const source = [
  '// Generated by scripts/build_book_sizes.mjs from the current PDFs and cover art.',
  `export const measuredSizes = ${JSON.stringify(sizes)}`,
  `export const coverSizes = ${JSON.stringify(styles)}`,
  '',
].join('\n')
await writeFile(new URL('book-size-data.js', editor), source)
