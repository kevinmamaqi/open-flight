import { objects } from '../apps/editor/assets/objects/activities.js'
import { readFile, stat, writeFile } from 'node:fs/promises'
import { appearanceArtPath, appearanceArtStyles, appearanceChoices, sheetChoices } from '../apps/editor/model-appearance.js'
// A sheet's own colours: retired butterfly sheets do not take the K3-only designs.
const choicesFor = (id) => sheetCatalog.some(entry => entry.id === id) ? sheetChoices(id) : appearanceChoices(id)
import { paperSizes, sheetCatalog, sheetLocales } from '../apps/editor/family-sheets.js'
import { createBook } from '../packages/print-export/family-book.js'

const editor = new URL('../apps/editor/', import.meta.url)
const assets = new Map()
function loadAsset(path) {
  if (!assets.has(path)) assets.set(path,readFile(new URL(path,editor)))
  return assets.get(path)
}
const coverSizes = {}
for (const {id,model} of [...sheetCatalog, ...objects.map(({id})=>({id,model:id}))]) {
  for (const {id:color} of choicesFor(id)) for (const style of appearanceArtStyles) {
    const path = appearanceArtPath(id,style,color)
    coverSizes[path] ??= (await stat(new URL(path,editor))).size
  }
}

const pair = sheetCatalog.filter(entry => entry.family === 'airplane').slice(0,2).map(entry=>entry.id)
const shared = sheetCatalog.filter(entry => entry.sharedGuide).slice(0,2).map(entry=>entry.id)
const sizes = {}
for (const lang of sheetLocales) {
  sizes[lang] = {}
  for (const paper of paperSizes) {
    const measure = async (sheets, appearances, activities) => (await createBook({lang,paper,sheets,appearances,activities},{loadAsset})).byteLength
    const singles = {}, colored = {}, duplicateNotes = {}
    for (const {id,model} of sheetCatalog) {
      singles[id] = await measure([id])
      for (const {id:color} of choicesFor(id).slice(1)) {
        const key = id + '/' + color
        colored[key] = await measure([id],{[model]:color}) - singles[id]
      }
    }
    const overlap = async ([a,b]) => singles[a] + singles[b] - await measure([a,b])
    const frontMatter = await overlap(pair)
    const sharedGuide = await overlap(shared) - frontMatter
    for (const {id, model, construction} of sheetCatalog) {
      if (construction !== 'k1') continue
      const classic = sheetCatalog.find(entry => entry.model === model && entry.construction === 'w1')
      if (classic) duplicateNotes[model] = await overlap([classic.id, id]) - frontMatter
    }
    const activityBytes = {}
    for (const {id} of objects) {
      activityBytes[id] = await measure([pair[0]], {}, [id]) - singles[pair[0]]
      for (const {id:color} of appearanceChoices(id).slice(1))
        colored[id+'/'+color] = await measure([pair[0]], {[id]:color}, [id]) - singles[pair[0]] - activityBytes[id]
    }
    const activitiesTogether = await measure([pair[0]], {}, objects.map(item => item.id)) - singles[pair[0]]
    const activityOverlap = (Object.values(activityBytes).reduce((sum, size) => sum + size, 0) - activitiesTogether) / (objects.length - 1)
    sizes[lang][paper] = { singles, frontMatter, sharedGuide, colored, duplicateNotes, activityBytes, activityOverlap }
  }
}
await writeFile(new URL('book-size-data.js',editor), [
  '// Generated by scripts/build_book_sizes.mjs from the current sheets, field notes and artwork.',
  'export const measuredSizes = ' + JSON.stringify(sizes),
  'export const coverSizes = ' + JSON.stringify(coverSizes),
  '',
].join('\n'))
